// Generate from PostgreSQL catalogs after applying migrations, rather than maintaining handwritten row types.
import pg from "pg";
import { writeFile } from "node:fs/promises";
const db = new pg.Client({ connectionString: process.env.TEST_DATABASE_URL });
if (!process.env.TEST_DATABASE_URL)
  throw new Error("Set TEST_DATABASE_URL to an isolated migrated database");
await db.connect();
const { rows } = await db.query(
  `select table_name,column_name,data_type,udt_name,is_nullable,column_default from information_schema.columns where table_schema='public' order by table_name,ordinal_position`,
);
const enums = (
  await db.query(
    `select t.typname,array_agg(e.enumlabel::text order by e.enumsortorder) labels from pg_type t join pg_enum e on e.enumtypid=t.oid join pg_namespace n on n.oid=t.typnamespace where n.nspname='public' group by t.typname`,
  )
).rows;
const enumMap = Object.fromEntries(
  enums.map((e) => [
    e.typname,
    e.labels.map((v) => JSON.stringify(v)).join(" | "),
  ]),
);
const js = (r) =>
  enumMap[r.udt_name] ||
  (r.data_type === "ARRAY"
    ? "string[]"
    : r.data_type === "jsonb"
      ? "Json"
      : ["integer", "bigint", "numeric", "double precision"].includes(
            r.data_type,
          )
        ? "number"
        : r.data_type === "boolean"
          ? "boolean"
          : "string");
let code =
  "// GENERATED by scripts/generate-database-types.mjs from applied PostgreSQL schema. Do not edit.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = { public: { Tables: {\n";
for (const table of [...new Set(rows.map((r) => r.table_name))]) {
  const columns = rows.filter((r) => r.table_name === table);
  const shape = (mode) =>
    columns
      .map(
        (r) =>
          `${JSON.stringify(r.column_name)}${mode === "Update" || (mode === "Insert" && (r.column_default !== null || r.is_nullable === "YES")) ? "?" : ""}: ${js(r)}${r.is_nullable === "YES" ? " | null" : ""}`,
      )
      .join("; ");
  code += `${JSON.stringify(table)}: { Row: { ${shape("Row")} }; Insert: { ${shape("Insert")} }; Update: { ${shape("Update")} }; Relationships: [] };\n`;
}
code +=
  "}; Views: Record<string, never>; Functions: { crm_snapshot: { Args: Record<string, never>; Returns: Json }; crm_command: { Args: { p_operation: string; p_command: Json }; Returns: Json }; ceo_authorized: { Args: Record<string, never>; Returns: boolean }; consume_auth_limit: { Args: { p_key: string }; Returns: boolean }; consume_request_limit: { Args: { p_scope: string }; Returns: boolean } }; Enums: {";
for (const [name, values] of Object.entries(enumMap))
  code += `${name}: ${values};`;
code += "}; CompositeTypes: Record<string, never> } };\n";
await writeFile(
  new URL("../src/contracts/database.types.ts", import.meta.url),
  code,
);
await db.end();
